// Couleur de chaque verdict d'affirmation (ensemble fermé défini dans
// src/lib/live-analyse.js : VERDICTS).
const VERDICT_STYLES = {
  "Cohérent": { dot: "bg-emerald-600", text: "text-emerald-700" },
  "Plutôt cohérent": { dot: "bg-green-500", text: "text-green-600" },
  "Incertain": { dot: "bg-amber-400", text: "text-amber-600" },
  "Non étayé": { dot: "bg-red-500", text: "text-red-600" },
  "Contredit": { dot: "bg-red-800", text: "text-red-800" },
};
const VERDICT_FALLBACK = { dot: "bg-zinc-300", text: "text-zinc-500" };

export function VerdictDot({ verdict }) {
  const style = VERDICT_STYLES[verdict] ?? VERDICT_FALLBACK;
  return <span aria-hidden="true" className={`mt-1.5 h-2.5 w-2.5 shrink-0 rounded-full ${style.dot}`} />;
}

export function VerdictLabel({ verdict, className = "" }) {
  const style = VERDICT_STYLES[verdict] ?? VERDICT_FALLBACK;
  return <span className={`shrink-0 text-sm font-medium ${style.text} ${className}`}>{verdict}</span>;
}

