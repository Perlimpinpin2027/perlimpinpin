// Photo du candidat (public/photos, champ Candidat.photoUrl) ; à défaut,
// pastille d'initiales.
export function Avatar({ nom, photoUrl, size = 40 }) {
  const style = { width: size, height: size };
  if (photoUrl) {
    return (
      // eslint-disable-next-line @next/next/no-img-element -- comme le reste du site (photos statiques de public/)
      <img src={photoUrl} alt="" aria-hidden="true" style={style} className="shrink-0 rounded-full object-cover" />
    );
  }
  const initiales = nom
    ? nom
        .split(/\s+/)
        .map((mot) => mot[0])
        .slice(0, 2)
        .join("")
        .toUpperCase()
    : "?";
  return (
    <span
      style={style}
      aria-hidden="true"
      className="flex shrink-0 items-center justify-center rounded-full bg-zinc-100 text-xs font-semibold text-zinc-500"
    >
      {initiales}
    </span>
  );
}

// Badge de score coloré selon le barème à 6 paliers du site (src/lib/score.js,
// même source que les fiches publiques).
export function ScoreBadge({ score }) {
  const badge = getScoreBadge(score);
  return (
    <span
      title={badge.label}
      className={`inline-flex shrink-0 items-baseline gap-1 rounded-full px-2.5 py-1 text-sm font-bold ${badge.badgeClass}`}
    >
      {score}
      <span className="text-[10px] font-semibold uppercase tracking-wide">{badge.label}</span>
    </span>
  );
}

